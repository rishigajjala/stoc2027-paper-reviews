from fractions import Fraction as F
import math,json,pathlib
checks={}
def check(n,b):checks[n]=bool(b)
def EL(x,d=48):return sum((x**j/F(math.factorial(j)) for j in range(d+1)),F(0))
def EU(x,d=48):return EL(x,d)+x**(d+1)/math.factorial(d+1)/(1-x/F(d+2))
def LL(x,q=48):
 z=(x-1)/(x+1);return 2*sum((z**(2*j+1)/F(2*j+1) for j in range(q)),F(0))
check('small means',EL(F(24,5))>10*F(17,5)**2)
check('large means',EL(F(25,9))>10)
check('small first mean',EL(F(389,100))>F(489,10))
c=F(673,200);check('prefix Chernoff',EL(2*(c-1))>10*c*c)
ap=F(11447,2025);check('prefix coefficient',1+F(112,81)*c==ap)
for i,v in enumerate([F(34,5)*F(14,25),3*F(15,16),F(9,4)*F(55,36),F(121,58)*F(100,37)]):check(f'small prefix {i}',v<ap)
for a,b in [(2,F(69,100)),(6,F(16,9)),(7,F(389,200)),(12,F(12,5)),(28,F(333,100))]:check(f'log {a}',LL(F(a),300)>b)
check('cube7',F(1913,1000)**3>7);check('cube16',F(63,25)**3>16)
check('round prefix total',F(1,32)+F(325,552)+F(25,69)==F(723,736));check('round prefix <1',F(723,736)<1)
Rp=ap+F(2,13);U=F(9,8)*Rp+F(1,3);check('U',U==F(160661,23400))
D=F(67,5);H0=F(49,4);theta0=F(265,268);r0=F(171,100);M=3*U*r0;C=M+D
check('M',M==F(9157677,260000));check('C',C==F(12641677,260000))
check('theta cap',(1+H0)/D==theta0);check('chord',EU(theta0)<1+r0*theta0)
check('late thinning',EL(F(19,40)*H0-theta0)>F(1773,20)/(r0-1))
check('early theta',(D*F(3,10)-3)*H0>3+D*F(7,10))
check('entropy payment',C/2>D*(1+1/EL(F(1))))
x=F(3,8);B=4*x**4/(1-x**4)**2;check('profile series',(1-x)**-3*(1-x*x)**-4/(1-B)-1<20*x)
check('layer decay',2**25>6**9)
check('exp3',EL(F(3))>20);check('pow2',2**25>F(5,2)**18)
s=F(335,18);tail=C+2*s+28*s*F(1,20)*F(2,5)/F(95,48)
check('chain integral',tail==F(4050751567,44460000));check('chain bound',tail<F(456,5))
K=F(5051,35)+F(149001,5000)+F(87077,3105)+F(11513,5000)
check('K sum',K==F(2221982179,10867500));check('909 closure',K*F(40,9)*(1+F(1,2**20))<909)
check('exp9',EU(F(9))<8200);check('top negligible',F(820000,69*2**26)<F(1,5000))
pathlib.Path('1566-arithmetic-checks.json').write_text(json.dumps(checks,indent=2))
print(len(checks),'checks',all(checks.values()),[k for k,v in checks.items() if not v])
